import { writeFileSync, readFileSync } from "node:fs";
const lines = [];
const L = (s) => { lines.push(s); };

L('');
L('kitsRouter.patch("/:id", requireKitOwnership, async (req, res) => {');
L('  const repo = req.app.locals.repo || (await getRepository());');
L('  const kit = req.kit;');
L('  const patch = {};');
L('  const body = req.body || {};');
L('');
L('  if (body.editQuestion) {');
L('    const { id, text, answerOutline, category, requirementIds } = body.editQuestion;');
L('    kit.questions = (kit.questions || []).map((q) => {');
L('      if (q.id !== id) return q;');
L('      const next = { ...q, state: "edited" };');
L('      if (text !== undefined) next.text = String(text);');
L('      if (answerOutline !== undefined) next.answerOutline = String(answerOutline);');
L('      if (category !== undefined) next.category = orEnum(category, ["technical", "behavioural", "product", "process", "company", "other"], q.category);');
L('      if (requirementIds !== undefined) next.requirementIds = requirementIds;');
L('      return next;');
L('    });');
L('    patch.questions = kit.questions;');
L('  }');
L('');
L('  if (body.editFlashcard) {');
L('    const { id, front, back, requirementIds } = body.editFlashcard;');
L('    kit.flashcards = (kit.flashcards || []).map((f) => {');
L('      if (f.id !== id) return f;');
L('      const next = { ...f, state: "edited" };');
L('      if (front !== undefined) next.front = String(front);');
L('      if (back !== undefined) next.back = String(back);');
L('      if (requirementIds !== undefined) next.requirementIds = requirementIds;');
L('      return next;');
L('    });');
L('    patch.flashcards = kit.flashcards;');
L('  }');
L('');
L('  if (body.brief !== undefined) {');
L('    kit.company = { ...kit.company, brief: String(body.brief), briefState: "edited" };');
L('    patch.company = kit.company;');
L('  }');
L('');
L('  if (body.roleSummary !== undefined) {');
L('    kit.role = { ...kit.role, summary: String(body.roleSummary), summaryState: "edited" };');
L('    patch.role = kit.role;');
L('  }');
L('');
L('  if (Array.isArray(body.reorderQuestions)) {');
L('    const ids = new Set(body.reorderQuestions);');
L('    const byId = new Map((kit.questions || []).map((q) => [q.id, q]));');
L('    const reordered = body.reorderQuestions.map((id) => byId.get(id)).filter(Boolean);');
L('    for (const q of kit.questions || []) if (!ids.has(q.id)) reordered.push(q);');
L('    kit.questions = reordered;');
L('    patch.questions = kit.questions;');
L('  }');
L('');
L('  if (body.addQuestion) {');
L('    const idGen = makeIdGen("q", (kit.questions || []).map((q) => q.id));');
L('    kit.questions = [...(kit.questions || []), {');
L('      id: idGen(),');
L('      category: orEnum(body.addQuestion.category, ["technical", "behavioural", "product", "process", "company", "other"], "other"),');
L('      requirementIds: Array.isArray(body.addQuestion.requirementIds) ? body.addQuestion.requirementIds : [],');
L('      text: String(body.addQuestion.text),');
L('      answerOutline: String(body.addQuestion.answerOutline || ""),');
L('      state: "created",');
L('    }];');
L('    patch.questions = kit.questions;');
L('  }');
L('');
L('  if (body.deleteQuestionId) {');
L('    kit.questions = (kit.questions || []).filter((q) => q.id !== body.deleteQuestionId);');
L('    patch.questions = kit.questions;');
L('  }');
L('');
L('  if (body.addFlashcard) {');
L('    const idGen = makeIdGen("f", (kit.flashcards || []).map((f) => f.id));');
L('    kit.flashcards = [...(kit.flashcards || []), {');
L('      id: idGen(), front: String(body.addFlashcard.front), back: String(body.addFlashcard.back),');
L('      requirementIds: Array.isArray(body.addFlashcard.requirementIds) ? body.addFlashcard.requirementIds : [],');
L('      state: "created", practice: { confidence: 0, reviewCount: 0 },');
L('    }];');
L('    patch.flashcards = kit.flashcards;');
L('  }');
L('');
L('  if (body.deleteFlashcardId) {');
L('    kit.flashcards = (kit.flashcards || []).filter((f) => f.id !== body.deleteFlashcardId);');
L('    patch.flashcards = kit.flashcards;');
L('  }');
L('');
L('  if (body.editDay) {');
L('    const { day, focus, questionIds, requirementIds, durationMinutes } = body.editDay;');
L('    kit.schedule = (kit.schedule || []).map((d) => {');
L('      if (d.day !== day) return d;');
L('      const next = { ...d };');
L('      if (focus !== undefined) next.focus = String(focus);');
L('      if (questionIds !== undefined) next.questionIds = questionIds;');
L('      if (requirementIds !== undefined) next.requirementIds = requirementIds;');
L('      if (durationMinutes !== undefined) next.durationMinutes = parseInt(durationMinutes, 10);');
L('      return next;');
L('    });');
L('    patch.schedule = kit.schedule;');
L('  }');
L('');
L('  patch.updatedAt = new Date().toISOString();');
L('  const updated = await repo.updateKit(kit.id, patch);');
L('  res.json({ kit: updated });');
L('});');

const prev = readFileSync("C:\\trao\\backend\\src\\routes\\kits.js", "utf8");
writeFileSync("C:\\trao\\backend\\src\\routes\\kits.js", prev + "\n" + lines.join("\n"));
