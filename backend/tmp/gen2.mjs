import { writeFileSync, readFileSync } from "node:fs";
const lines = [];
const L = (s) => { lines.push(s); };

L('');
L('kitsRouter.get("/:id/stream", requireAuth, async (req, res) => {');
L('  const repo = req.app.locals.repo || (await getRepository());');
L('  const kit = await repo.findKitById(req.params.id);');
L('  if (!kit) return res.status(404).end();');
L('  if (kit.userId && kit.userId !== req.userId) return res.status(403).end();');
L('  if (kit.status === "complete" || kit.status === "partial" || kit.status === "failed") {');
L('    res.writeHead(200, { "Content-Type": "text/event-stream", "Cache-Control": "no-cache", Connection: "keep-alive" });');
L('    res.write("event: kit\\ndata: " + JSON.stringify(kit) + "\\n\\n");');
L('    res.write("event: done\\ndata: {}\\n\\n");');
L('    return res.end();');
L('  }');
L('  res.writeHead(200, { "Content-Type": "text/event-stream", "Cache-Control": "no-cache, no-transform", Connection: "keep-alive" });');
L('  res.write("event: ready\\ndata: {}\\n\\n");');
L('  if (req.flushHeaders) req.flushHeaders();');
L('  try {');
L('    const result = await runPipeline(');
L('      { jd: kit.input.jd, companyUrl: kit.input.companyUrl, days: kit.input.days },');
L('      { kitId: kit.id, userId: req.userId, emit: (e) => res.write("event: " + e.type + "\\ndata: " + JSON.stringify(e) + "\\n\\n"), gen: generateJson }');
L('    );');
L('    await repo.updateKit(kit.id, result.kit);');
L('    res.write("event: kit\\ndata: " + JSON.stringify(result.kit) + "\\n\\n");');
L('    res.write("event: done\\ndata: " + JSON.stringify({ ok: result.ok }) + "\\n\\n");');
L('  } catch (e) {');
L('    const failed = { ...kit, status: "failed", valid: false, validationErrors: [e.message || String(e)], updatedAt: new Date().toISOString() };');
L('    await repo.updateKit(kit.id, failed);');
L('    res.write("event: kit\\ndata: " + JSON.stringify(failed) + "\\n\\n");');
L('    res.write("event: done\\ndata: " + JSON.stringify({ ok: false, error: e.message }) + "\\n\\n");');
L('  } finally {');
L('    res.end();');
L('  }');
L('});');

const prev = readFileSync("C:\\trao\\backend\\src\\routes\\kits.js", "utf8");
writeFileSync("C:\\trao\\backend\\src\\routes\\kits.js", prev + "\n" + lines.join("\n"));
