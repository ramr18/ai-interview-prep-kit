import { writeFileSync, readFileSync } from "node:fs";
const lines = [];
const L = (s) => { lines.push(s); };

L('');
L('kitsRouter.post("/:id/regenerate/:section", requireKitOwnership, async (req, res) => {');
L('  const repo = req.app.locals.repo || (await getRepository());');
L('  const kit = req.kit;');
L('  const section = req.params.section;');
L('  const body = req.body || {};');
L('  const patch = {};');
L('');
L('  if (section === "brief") {');
L('    const fresh = await generateJson({');
L('      step: "brief",');
L('      payload: {');
L('        companyName: kit.company?.name || "", companyUrl: kit.input?.companyUrl || "",');
L('        aboutSummary: kit.research?.aboutSummary || "",');
L('        hiringSummary: kit.company?.hiringProcess?.found ? kit.company.hiringProcess.summary : "",');
L('        discussionSummary: kit.research?.discussionSummary || "", sources: kit.sources || [],');
L('      },');
L('      maxOutputTokens: 1200,');
L('    });');
L('    const result = regenerateScalar(kit.company?.brief, kit.company?.briefState, fresh.brief || "");');
L('    patch.company = { ...kit.company, brief: result.value, briefState: result.state };');
L('  } else if (section === "roleSummary") {');
L('    const fresh = await generateJson({');
L('      step: "roleSummary",');
L('      payload: {');
L('        title: kit.role?.title || "", jd: kit.input?.jd || "",');
L('        requirements: kit.role?.requirements || [], thinDescription: kit.notes?.thinDescription || false,');
L('        gapCount: kit.gaps?.length || 0,');
L('      },');
L('      maxOutputTokens: 1200,');
L('    });');
L('    const result = regenerateScalar(kit.role?.summary, kit.role?.summaryState, fresh.summary || "");');
L('    patch.role = { ...kit.role, summary: result.value, summaryState: result.state };');
L('  } else if (section === "flashcards") {');
L('    const fresh = await generateJson({');
L('      step: "flashcards",');
L('      payload: {');
L('        requirements: kit.role?.requirements || [], questions: kit.questions || [],');
L('        companyFacts: [kit.research?.aboutSummary, kit.company?.hiringProcess?.summary].filter(Boolean).join("\\n"),');
L('      },');
L('      maxOutputTokens: 4000,');
L('    });');
L('    const idGen = makeIdGen("f", (kit.flashcards || []).map((f) => f.id));');
L('    const freshCards = (fresh.flashcards || []).map((c) => ({');
L('      id: idGen(), front: c.front, back: c.back, requirementIds: c.requirementIds || [],');
L('      state: GENERATED_STATE, practice: { confidence: 0, reviewCount: 0 },');
L('    }));');
L('    patch.flashcards = regenerateFlashcards(kit.flashcards || [], freshCards);');
L('  } else if (section === "schedule") {');
L('    const sched = allocateSchedule({');
L('      days: kit.input?.days || 7, requirements: kit.role?.requirements || [], questions: kit.questions || [],');
L('    });');
L('    patch.schedule = sched.schedule;');
L('  } else if (section === "questions") {');
L('    const category = String(body.category || "other");');
L('    const reqs = (kit.role?.requirements || []).filter((r) => r.category === category);');
L('    const fresh = await generateJson({');
L('      step: "questions",');
L('      payload: {');
L('        category, requirements: reqs, companyName: kit.company?.name || "",');
L('        companyContext: [kit.research?.aboutSummary, kit.research?.whatTheyDo].filter(Boolean).join("\\n"),');
L('        hiringContext: kit.company?.hiringProcess?.summary || "",');
L('      },');
L('      maxOutputTokens: 4000,');
L('    });');
L('    const idGen = makeIdGen("q", (kit.questions || []).map((q) => q.id));');
L('    const freshQs = (fresh.questions || []).map((q) => ({');
L('      id: idGen(), category, requirementIds: q.requirementIds || [],');
L('      text: q.text, answerOutline: q.answerOutline || "", state: GENERATED_STATE,');
L('    }));');
L('    patch.questions = regenerateCategoryQuestions(kit.questions || [], category, freshQs);');
L('  } else {');
L('    return res.status(400).json({ error: "unknown_section", message: "Cannot regenerate \\"" + section + "\\"" });');
L('  }');
L('');
L('  patch.updatedAt = new Date().toISOString();');
L('  const updated = await repo.updateKit(kit.id, patch);');
L('  res.json({ kit: updated });');
L('});');

const prev = readFileSync("C:\\trao\\backend\\src\\routes\\kits.js", "utf8");
writeFileSync("C:\\trao\\backend\\src\\routes\\kits.js", prev + "\n" + lines.join("\n"));
